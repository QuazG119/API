CREATE OR REPLACE PROCEDURE PAR.OSU4R_TKBTv2_Deployment_GetHistoryDeploymentNotOk (
  p_SupId  IN  NUMBER,
  p_result OUT SYS_REFCURSOR
) AS
BEGIN
  OPEN p_result FOR
    SELECT ID, SUP_ID, DESCRIPTION, ACCOUNT_MODIFY, STATUS, CREATED_DATE
    FROM   PAR.DEPLOYMENT_HISTORY
    WHERE  SUP_ID = p_SupId
    ORDER  BY CREATED_DATE DESC;
END;
/

